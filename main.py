import streamlit as st
import pandas as pd
import plotly.express as px
from scipy.stats import pearsonr

# -----------------------------------
# 1. 페이지 설정
# -----------------------------------
st.set_page_config(
    page_title="청소년 건강행태 상관관계 분석",
    page_icon="📊",
    layout="wide"
)

st.title("📊 청소년 아침식사 결식률과 신체활동 실천율")
st.markdown("""
### 두 변수 사이에는 정말 유의미한 관계가 있을까?
질병관리청 청소년건강행태조사 통계를 활용한 데이터 분석
""")

st.divider()

# -----------------------------------
# 2. 공식 공개 통계 데이터
# 단위: %
# -----------------------------------
data = [
    [2016, "남학생", 27.3, 18.8],
    [2017, "남학생", 30.1, 19.5],
    [2018, "남학생", 32.2, 20.3],
    [2019, "남학생", 34.6, 21.5],
    [2020, "남학생", 35.5, 19.9],
    [2021, "남학생", 37.0, 20.7],
    [2022, "남학생", 37.4, 23.4],
    [2023, "남학생", 39.7, 24.6],
    [2024, "남학생", 40.2, 25.1],
    [2025, "남학생", 41.9, 24.5],

    [2016, "여학생", 29.3, 7.0],
    [2017, "여학생", 33.0, 7.5],
    [2018, "여학생", 35.1, 7.1],
    [2019, "여학생", 36.9, 7.3],
    [2020, "여학생", 39.2, 7.7],
    [2021, "여학생", 39.1, 8.1],
    [2022, "여학생", 40.7, 8.8],
    [2023, "여학생", 42.6, 9.2],
    [2024, "여학생", 44.7, 8.9],
    [2025, "여학생", 45.3, 8.5],
]

df = pd.DataFrame(
    data,
    columns=[
        "연도",
        "성별",
        "아침식사 결식률",
        "신체활동 실천율"
    ]
)

# -----------------------------------
# 3. 사이드바
# -----------------------------------
st.sidebar.header("📌 분석 설정")

gender = st.sidebar.selectbox(
    "분석할 성별",
    ["전체", "남학생", "여학생"]
)

if gender == "전체":
    selected_df = df.copy()
else:
    selected_df = df[df["성별"] == gender].copy()

# -----------------------------------
# 4. 핵심 통계
# -----------------------------------
st.subheader("1. 주요 통계 현황")

col1, col2 = st.columns(2)

with col1:
    st.metric(
        "2025년 남학생 아침식사 결식률",
        "41.9%"
    )

with col2:
    st.metric(
        "2025년 여학생 아침식사 결식률",
        "45.3%"
    )

st.caption(
    "출처: 질병관리청 청소년건강행태조사, 2025년"
)

# -----------------------------------
# 5. 연도별 추이 그래프
# -----------------------------------
st.subheader("2. 연도별 건강행태 변화")

fig1 = px.line(
    selected_df,
    x="연도",
    y=["아침식사 결식률", "신체활동 실천율"],
    color="성별",
    markers=True,
    title="아침식사 결식률과 신체활동 실천율 추이",
    labels={
        "value": "비율 (%)",
        "variable": "건강 지표",
        "연도": "연도"
    }
)

fig1.update_layout(
    hovermode="x unified",
    yaxis_title="비율 (%)",
    legend_title="성별"
)

st.plotly_chart(fig1, use_container_width=True)

# -----------------------------------
# 6. 막대그래프
# -----------------------------------
st.subheader("3. 성별 건강행태 비교")

fig2 = px.bar(
    selected_df,
    x="연도",
    y=["아침식사 결식률", "신체활동 실천율"],
    barmode="group",
    color_discrete_sequence=["#EF553B", "#636EFA"],
    title="연도별 아침식사 결식률과 신체활동 실천율"
)

st.plotly_chart(fig2, use_container_width=True)

